//! Generation of the `tunnel-client` YAML profiles.
//!
//! One profile per definition, rewritten on every start at
//! `<tunnels>\profiles\<id>.yaml` and passed to the runtime as
//! `tunnel-client run --profile-file <path>`. The generated subset follows
//! the official `config_version: 1` schema:
//!
//! ```yaml
//! config_version: 1
//! control_plane:
//!   base_url: 'https://api.openai.com'
//!   tunnel_id: 'tunnel_0123456789abcdef0123456789abcdef'
//!   api_key: 'file:C:\...\tunnels\secrets\files.key'
//! log:
//!   level: info
//!   format: json
//!   file: 'C:\...\tunnels\logs\files.log'
//! health:
//!   listen_addr: '127.0.0.1:18080'
//! mcp:
//!   server_urls:
//!   - channel: main
//!     url: 'http://127.0.0.1:3000/mcp'
//! ```
//!
//! (a stdio target emits `mcp.commands: [{channel: main, command: ...}]`
//! instead of `server_urls`).
//!
//! Every scalar is single-quoted: YAML single-quoted scalars keep Windows
//! backslashes verbatim, and doubling handles the one special character
//! (a literal single quote). The api-key value uses the reference forms the
//! client documents (`env:VARNAME`, `file:<path>`); key material itself
//! never appears in a profile except through such a reference, and never
//! crosses the IPC boundary at all.

use std::path::Path;

use crate::error::{McpGoError, McpGoResult};

use super::definition::{
    ApiKeySource, ApiKeySourceKind, TunnelDefinition, TunnelTargetKind,
};

/// Schema version header every generated profile carries.
const CONFIG_VERSION: u32 = 1;
/// Log level of the runtime (the UI renders the file, so structured output
/// is the useful one).
const LOG_LEVEL: &str = "info";
/// Log format: one JSON object per line (ndjson) - trivial to read back and
/// display verbatim in the log panel.
const LOG_FORMAT: &str = "json";

/// Builds the YAML profile of `definition` for health port `port`. Pure
/// function (string assembly) so it is unit-testable without a file
/// system: `log_path` is the absolute `log.file` value (the canonical
/// `<tunnels>\logs\<id>.log` owned by the store).
pub fn render(
    definition: &TunnelDefinition,
    api_key_reference: &str,
    port: u16,
    log_path: &Path,
) -> String {
    let mut yaml = String::new();
    yaml.push_str("# Generated by McpGo-Windows - rewritten on every start.\n");
    yaml.push_str("# Runtime: tunnel-client run --profile-file <this file>\n");
    yaml.push_str(&format!("config_version: {CONFIG_VERSION}\n"));

    yaml.push_str("control_plane:\n");
    yaml.push_str(&format!(
        "  base_url: {}\n",
        yaml_quote(definition.residency.base_url())
    ));
    yaml.push_str(&format!("  tunnel_id: {}\n", yaml_quote(&definition.tunnel_id)));
    yaml.push_str(&format!("  api_key: {}\n", yaml_quote(api_key_reference)));

    yaml.push_str("log:\n");
    yaml.push_str(&format!("  level: {LOG_LEVEL}\n"));
    yaml.push_str(&format!("  format: {LOG_FORMAT}\n"));
    yaml.push_str(&format!(
        "  file: {}\n",
        yaml_quote(&log_path.to_string_lossy())
    ));

    yaml.push_str("health:\n");
    yaml.push_str(&format!("  listen_addr: {}\n", yaml_quote(&format!("127.0.0.1:{port}"))));

    yaml.push_str("mcp:\n");
    match definition.target_kind {
        TunnelTargetKind::Http => {
            let url = definition
                .server_url
                .as_deref()
                .unwrap_or_default()
                .to_owned();
            yaml.push_str("  server_urls:\n");
            yaml.push_str("  - channel: main\n");
            yaml.push_str(&format!("    url: {}\n", yaml_quote(&url)));
        }
        TunnelTargetKind::Stdio => {
            yaml.push_str("  commands:\n");
            yaml.push_str("  - channel: main\n");
            yaml.push_str(&format!(
                "    command: {}\n",
                yaml_quote(&command_line(definition))
            ));
        }
    }
    yaml
}

/// Composes the api-key reference of a definition for the
/// `control_plane.api_key` field: `file:<secret path>` for managed keys,
/// `env:<name>` / `file:<path>` for the explicit sources. Never contains
/// key material itself.
pub fn api_key_reference(definition: &TunnelDefinition, secret_path: &Path) -> String {
    match &definition.api_key {
        ApiKeySource {
            kind: ApiKeySourceKind::Managed,
            ..
        } => format!("file:{}", secret_path.display()),
        ApiKeySource {
            kind: ApiKeySourceKind::Env,
            reference: Some(name),
        } => format!("env:{name}"),
        ApiKeySource {
            kind: ApiKeySourceKind::File,
            reference: Some(path),
        } => format!("file:{path}"),
        // Validation guarantees a reference for env/file; a corrupt file
        // with a missing reference falls back to an empty literal, which
        // the runtime rejects with a clear configuration error.
        _ => String::new(),
    }
}

/// Joins the stdio command and arguments into the single command line the
/// client's `mcp.commands[].command` field expects. Tokens containing
/// whitespace are double-quoted; embedded double quotes are rejected at
/// validation time (see `definition::validate_input`), so this quoting is
/// unambiguous.
fn command_line(definition: &TunnelDefinition) -> String {
    let mut tokens: Vec<String> = Vec::new();
    if let Some(command) = definition.command.as_deref() {
        tokens.push(quote_token(command));
    }
    tokens.extend(definition.args.iter().map(|arg| quote_token(arg)));
    tokens.join(" ")
}

/// Wraps one command token in double quotes when it contains whitespace.
fn quote_token(token: &str) -> String {
    if token.chars().any(char::is_whitespace) {
        format!("\"{token}\"")
    } else {
        token.to_owned()
    }
}

/// Renders a YAML single-quoted scalar (backslashes verbatim, embedded
/// single quotes doubled).
fn yaml_quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "''"))
}

/// Writes the profile of `definition` (for health port `port`) to
/// `profile_path` atomically. The log record of the caller carries the
/// path only, never the content - it contains a secret reference.
pub fn write(
    definition: &TunnelDefinition,
    api_key_reference: &str,
    port: u16,
    profile_path: &Path,
    log_path: &Path,
) -> McpGoResult<()> {
    let yaml = render(definition, api_key_reference, port, log_path);
    let tmp = profile_path.with_extension("tmp");
    std::fs::write(&tmp, yaml.as_bytes())
        .map_err(|e| McpGoError::io("write the tunnel-client profile", &e))?;
    let _ = std::fs::remove_file(profile_path);
    std::fs::rename(&tmp, profile_path)
        .map_err(|e| McpGoError::io("write the tunnel-client profile", &e))?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::tunnels::definition::Residency;

    fn definition(target: TunnelTargetKind) -> TunnelDefinition {
        TunnelDefinition {
            id: "files".into(),
            name: "Files".into(),
            description: String::new(),
            tunnel_id: "tunnel_0123456789abcdef0123456789abcdef".into(),
            target_kind: target,
            command: Some("node".into()),
            args: vec!["C:\\My Servers\\mcp-server.js".into(), "--stdio".into()],
            working_dir: None,
            server_url: Some("http://127.0.0.1:3000/mcp".into()),
            api_key: ApiKeySource {
                kind: ApiKeySourceKind::Managed,
                reference: None,
            },
            residency: Residency::Eu,
            autostart: false,
            keep_alive: true,
            client_path: None,
            health_port: Some(18080),
            created_at: 0,
            updated_at: 0,
        }
    }

    #[test]
    fn renders_the_documented_schema() {
        let def = definition(TunnelTargetKind::Http);
        let secret = Path::new(r"C:\Data\com.mcpgo.windows\tunnels\secrets\files.key");
        let log = Path::new(r"C:\Data\com.mcpgo.windows\tunnels\logs\files.log");
        let reference = api_key_reference(&def, secret);
        assert_eq!(
            reference,
            r"file:C:\Data\com.mcpgo.windows\tunnels\secrets\files.key"
        );

        let yaml = render(&def, &reference, 18123, log);
        let lines: Vec<&str> = yaml.lines().collect();
        assert!(lines.contains(&"config_version: 1"));
        assert!(lines.contains(&"  base_url: 'https://eu.api.openai.com'"));
        assert!(lines.contains(&"  tunnel_id: 'tunnel_0123456789abcdef0123456789abcdef'"));
        assert!(lines.contains(&format!("  api_key: '{reference}'")));
        assert!(lines.contains(&"  listen_addr: '127.0.0.1:18123'"));
        assert!(lines.contains(
            "  file: 'C:\\Data\\com.mcpgo.windows\\tunnels\\logs\\files.log'"
        ));
        // The HTTP target binds the main channel to the server URL.
        assert!(lines.contains(&"  server_urls:"));
        assert!(lines.contains(&"  - channel: main"));
        assert!(lines.contains(&"    url: 'http://127.0.0.1:3000/mcp'"));
        assert!(!yaml.contains("commands:"));
    }

    #[test]
    fn stdio_targets_render_the_main_command() {
        let def = definition(TunnelTargetKind::Stdio);
        let log = Path::new(r"C:\Data\com.mcpgo.windows\tunnels\logs\files.log");
        let yaml = render(&def, "env:CONTROL_PLANE_API_KEY", 18080, log);
        assert!(yaml.contains("  commands:\n"));
        assert!(yaml.contains("  - channel: main\n"));
        // The token with a space is quoted, the flag is not.
        assert!(yaml.contains(
            "    command: 'node \"C:\\My Servers\\mcp-server.js\" --stdio'\n"
        ));
        assert!(!yaml.contains("server_urls:"));
    }

    #[test]
    fn api_key_reference_forms() {
        let mut def = definition(TunnelTargetKind::Http);
        let secret = Path::new(r"C:\Data\secrets\files.key");
        assert_eq!(
            api_key_reference(&def, secret),
            r"file:C:\Data\secrets\files.key"
        );

        def.api_key = ApiKeySource {
            kind: ApiKeySourceKind::Env,
            reference: Some("CONTROL_PLANE_API_KEY".into()),
        };
        assert_eq!(api_key_reference(&def, secret), "env:CONTROL_PLANE_API_KEY");

        def.api_key = ApiKeySource {
            kind: ApiKeySourceKind::File,
            reference: Some(r"C:\Data\my.key".into()),
        };
        assert_eq!(api_key_reference(&def, secret), r"file:C:\Data\my.key");
    }

    #[test]
    fn yaml_quoting_keeps_backslashes_and_escapes_quotes() {
        assert_eq!(yaml_quote(r"C:\Data\files.key"), r"'C:\Data\files.key'");
        assert_eq!(yaml_quote("it's"), "''it''s''");
    }
}
